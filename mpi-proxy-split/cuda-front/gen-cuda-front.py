#!/usr/bin/env python3
"""Generate a front library of a CUDA library for MANA's upper half.

  gen-cuda-front.py --real=LIB --prefix=P --out-dir=DIR [--header=H]
                    [--cxx=CXX --cflags=FLAGS] [--own=FILE]
                    [--unsupported=FILE]

Under --cuda, the application's CUDA libraries run in the lower half
(cuda/DESIGN-lower-half-cuda.md).  The upper half loads a front library in
their place, with the same exported functions and symbol versions.  Each
function is one of:

  own          written by hand (listed in --own); nothing is generated;
  auto         declared in header H: a trampoline to FrontAuto<decltype(f)>
               (front_auto.h), which takes the checkpoint gate, translates
               virtual streams and events, and calls the lower half's
               function; a function whose parameters have other handles or
               callbacks aborts, by its types;
  unsupported  listed in --unsupported, or not declared in H: aborts with
               the function's name.

A _ptds/_ptsz variant whose base function is auto uses the base's type.

Outputs DIR/P-tramp.S (the exported functions), DIR/P-gen.cpp (dispatch
table, names) and DIR/P.map (version script).
"""
import os
import re
import subprocess
import sys

opts = {}
for arg in sys.argv[1:]:
  if not arg.startswith("--") or "=" not in arg:
    sys.exit("usage: see the docstring of " + sys.argv[0])
  key, _, value = arg[2:].partition("=")
  opts[key] = value
real, prefix, out_dir = opts["real"], opts["prefix"], opts["out-dir"]


def read_list(path):
  names = set()
  if path:
    for line in open(path):
      line = line.split("#")[0].strip()
      if line:
        names.add(line)
  return names


own = read_list(opts.get("own"))
unsupported = read_list(opts.get("unsupported"))

# readelf, not nm: the front must have the real library's symbol versions.
# A line is  NUM: VALUE SIZE TYPE BIND VISIBILITY [NOTES] NDX NAME[@[@]VER]
syms = subprocess.run(["readelf", "-W", "--dyn-syms", real],
                      stdout=subprocess.PIPE, universal_newlines=True,
                      check=True).stdout
funcs, node = [], None
for line in syms.splitlines():
  parts = line.split()
  if parts and parts[-1].startswith("(") and parts[-1].endswith(")"):
    parts = parts[:-1]
  if len(parts) < 8 or not parts[0].endswith(":"):
    continue
  kind, bind, ndx, full = parts[3], parts[4], parts[-2], parts[-1]
  if ndx in ("UND", "ABS") or bind == "LOCAL" or kind not in ("FUNC", "IFUNC"):
    continue
  name = full.split("@")[0]
  if "@@" in full:
    node = full.split("@@")[1]
  if name not in funcs:
    funcs.append(name)

# The functions that header H declares (after preprocessing, so that
# cuda.h's '#define cuMemAlloc cuMemAlloc_v2' gives the _v2 name).
declared = set()
if opts.get("header"):
  cxx = opts.get("cxx", "g++")
  src = "#include <%s>\n" % opts["header"]
  pre = subprocess.run([cxx, "-E", "-P", "-x", "c++", "-"] +
                       opts.get("cflags", "").split(),
                       input=src, stdout=subprocess.PIPE,
                       universal_newlines=True, check=True).stdout
  declared = set(re.findall(r"\b([A-Za-z_]\w*)\s*\(", pre))

entries = []                  # (name, base or None) for every non-own one
for name in funcs:
  if name in own:
    continue
  base = None
  if name not in unsupported:
    if name in declared:
      base = name
    else:
      stem = re.sub(r"_(ptds|ptsz)$", "", name)
      if stem != name and stem in declared and stem not in own | unsupported:
        base = stem
  entries.append((name, base))

os.makedirs(out_dir, exist_ok=True)
table = "front_%s_dispatch" % prefix
with open(os.path.join(out_dir, prefix + "-tramp.S"), "w") as f:
  f.write("// Generated by gen-cuda-front.py from %s.  Do not edit.\n" % real)
  f.write("\t.text\n")
  for i, (name, _) in enumerate(entries):
    f.write("\t.globl %s\n\t.type %s, @function\n%s:\n"
            "\tjmp *%s+%d(%%rip)\n\t.size %s, .-%s\n"
            % (name, name, name, table, 8 * i, name, name))
  f.write('\t.section .note.GNU-stack,"",@progbits\n')

with open(os.path.join(out_dir, prefix + "-gen.cpp"), "w") as f:
  f.write("// Generated by gen-cuda-front.py from %s.  Do not edit.\n" % real)
  f.write('#include "front_auto.h"\n')
  if opts.get("header"):
    f.write("#include <%s>\n" % opts["header"])
  f.write("\nstatic const char *const names[] = {\n")
  for name, _ in entries:
    f.write('  "%s",\n' % name)
  f.write("};\n")
  f.write("static void *real[%d];\n" % max(len(entries), 1))
  f.write('FrontLib front_%s_lib = { "%s", names, real, %d, 0 };\n'
          % (prefix, os.path.basename(real), len(entries)))
  f.write("\nextern \"C\" FRONT_HIDDEN void *const %s[] = {\n" % table)
  for i, (name, base) in enumerate(entries):
    if base:
      f.write("  FRONT_AUTO(%s, %s, %d),\n" % (prefix, base, i))
    else:
      f.write("  FRONT_UNSUPPORTED(%s, %d),\n" % (prefix, i))
  f.write("};\n")

with open(os.path.join(out_dir, prefix + ".map"), "w") as f:
  f.write("%s {\n  global:\n" % (node or ""))
  for name in funcs:
    f.write("    %s;\n" % name)
  f.write("    mana_cuda_*;\n  local:\n    *;\n};\n")

n_auto = sum(1 for _, base in entries if base)
print("%s: %d functions: %d own, %d auto, %d unsupported"
      % (prefix, len(funcs), len(funcs) - len(entries), n_auto,
         len(entries) - n_auto))
