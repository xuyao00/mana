// For the hand-written wrappers of the shims: 'result' = 'call', an
// upper-half function, called with this thread's upper-half FS, or
// 'fallback' if this thread has no upper half.
#define FWD_CALL_UPPER(result, fallback, call) \
  do { \
    unsigned long uh_ = mana_fwd_uhfs(); \
    unsigned long lh_ = mana_fwd_current_fs(); \
    if (uh_ == 0) { \
      result = (fallback); \
    } else { \
      unsigned long t_ = mana_fwd_profiling > 0 ? __builtin_ia32_rdtsc() : 0; \
      mana_fwd_switch(uh_); \
      result = (call); \
      mana_fwd_switch(lh_); \
      if (t_ != 0) { \
        mana_fwd_prof_special(__func__, t_); \
      } \
    } \
  } while (0)

// MANA_FWD_PROFILE (fwd-runtime.c): > 0 when on.
extern int mana_fwd_profiling;
void mana_fwd_prof_special(const char *func, unsigned long t0);

