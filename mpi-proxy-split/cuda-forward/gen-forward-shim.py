#!/usr/bin/env python3
"""Generate a forwarding shim of a shared library for MANA's lower half.

  gen-forward-shim.py [--header=H --cxx=CXX] REAL_LIB SONAME PREFIX OUT_DIR
                      [EXCLUDED_SYMBOL ...]

For every function that REAL_LIB exports, the shim (OUT_DIR/PREFIX-tramp.S,
OUT_DIR/PREFIX-desc.c) defines a trampoline that forwards the call to the
same symbol of SONAME in the upper half (see fwd-runtime.c, fwd-tramp.inc).
Exported data symbols get dummies.  EXCLUDED_SYMBOLs get no trampoline: a
hand-written C wrapper defines them (e.g. cuGetProcAddress, whose results
must be wrapped, too).

With --header, the functions that header H declares with all arguments and
the result in registers get a fast trampoline (FWD_FAST_SLOT).  A C++
program, compiled with CXX, classifies them by their declared types.
"""
import os
import re
import subprocess
import sys
import tempfile

opts = {}
args = sys.argv[1:]
while args and args[0].startswith("--"):
  key, _, value = args.pop(0)[2:].partition("=")
  opts[key] = value
real, soname, prefix, out_dir = args[:4]
excluded = set(args[4:])

# readelf, not nm: some nm builds (SUSE's binutils 2.45) do not print symbol
# versions, and the shim must have the real library's.  A line is
#   NUM: VALUE SIZE TYPE BIND VISIBILITY [NOTES] NDX NAME[@[@]VERSION] [(IDX)]
syms = subprocess.run(["readelf", "-W", "--dyn-syms", real],
                      stdout=subprocess.PIPE, universal_newlines=True,
                      check=True).stdout
funcs, data = [], []
versions = {}                 # version node -> symbols
for line in syms.splitlines():
  parts = line.split()
  if parts and parts[-1].startswith("(") and parts[-1].endswith(")"):
    parts = parts[:-1]        # the version index
  if len(parts) < 8 or not parts[0].endswith(":"):
    continue
  kind, bind, ndx, full = parts[3], parts[4], parts[-2], parts[-1]
  if ndx in ("UND", "ABS") or bind == "LOCAL":
    continue
  name = full.split("@")[0]
  if "@@" in full:
    versions.setdefault(full.split("@@")[1], []).append(name)
  if name in excluded or name in funcs or name in data:
    continue
  if kind in ("FUNC", "IFUNC"):
    funcs.append(name)
  elif kind == "OBJECT":
    data.append(name)


# The x86-64 System V classes of the C++ types: a function whose arguments
# are all integers, pointers, enums, floats or doubles (at most 6 and 8 of
# them), not variadic, with such a result or none, has nothing on the stack.
CLASSIFY = r"""
#include <cstdio>
#include <type_traits>
#include HEADER
template <class T> constexpr int cls() {
  return std::is_integral<T>::value || std::is_pointer<T>::value ||
         std::is_enum<T>::value ? 0 :
         std::is_same<T, float>::value || std::is_same<T, double>::value ? 1 :
         -1;
}
template <class F> struct regs { static constexpr bool ok = false; };
template <class R, class... A> struct regs<R(A...)> {
  static constexpr bool ok =
    (true && ... && (cls<A>() >= 0)) &&
    (std::is_void<R>::value || cls<R>() >= 0) &&
    (0 + ... + (cls<A>() == 0)) <= 6 && (0 + ... + (cls<A>() == 1)) <= 8;
};
template <class R, class... A> struct regs<R(A...) noexcept> : regs<R(A...)> {};
#define F(name) std::printf("%s %d\n", #name, (int)regs<decltype(name)>::ok);
int main() {
NAMES
}
"""

def fast_functions(names):
  """The functions in 'names' that can have a fast trampoline."""
  if "header" not in opts:
    return set()
  cxx = opts.get("cxx", "g++").split()
  hdr = "<%s>" % opts["header"]
  try:
    pre = subprocess.run(cxx + ["-E", "-x", "c++", "-"], input="#include %s\n" % hdr,
                         stdout=subprocess.PIPE, universal_newlines=True,
                         check=True).stdout
    declared = set(re.findall(r"\b([A-Za-z_]\w*)\s*\(", pre))
    cands = [n for n in names if n in declared]
    with tempfile.TemporaryDirectory() as tmp:
      src, exe = os.path.join(tmp, "classify.cpp"), os.path.join(tmp, "classify")
      with open(src, "w") as f:
        f.write(CLASSIFY.replace("HEADER", hdr)
                .replace("NAMES", "".join("F(%s)\n" % n for n in cands)))
      subprocess.run(cxx + ["-std=c++17", "-Wno-deprecated-declarations", "-o",
                      exe, src], check=True)
      out = subprocess.run([exe], stdout=subprocess.PIPE,
                           universal_newlines=True, check=True).stdout
  except (OSError, subprocess.CalledProcessError) as e:
    sys.stderr.write("gen-forward-shim.py: no fast trampolines for %s: %s\n"
                     % (prefix, e))
    return set()
  return {l.split()[0] for l in out.splitlines() if l.endswith(" 1")}

fast = fast_functions(funcs)

desc = "mana_fwd_%s_lib" % prefix
with open(os.path.join(out_dir, prefix + "-tramp.S"), "w") as f:
  f.write("/* Generated by gen-forward-shim.py from %s. */\n" % real)
  f.write('#include "fwd-tramp.inc"\n\n')
  f.write("FWD_COMMON %s, fwd_%s_common, fwd_%s_ret\n" % (desc, prefix, prefix))
  if fast:
    f.write("FWD_FAST %s, fwd_%s_pre, fwd_%s_post\n" % (desc, prefix, prefix))
  f.write("\n")
  for i, name in enumerate(funcs):
    if name in fast:
      f.write("FWD_FAST_SLOT %s, %d, fwd_%s_pre, fwd_%s_post, fwd_%s_common\n"
              % (name, i, prefix, prefix, prefix))
    else:
      f.write("FWD_SLOT %s, %d, fwd_%s_common\n" % (name, i, prefix))
  f.write('\n  .section .note.GNU-stack,"",@progbits\n')

with open(os.path.join(out_dir, prefix + "-desc.c"), "w") as f:
  f.write("/* Generated by gen-forward-shim.py from %s. */\n" % real)
  f.write('#include "fwd-runtime.h"\n\n')
  f.write("static const char *names[] = {\n")
  for name in funcs:
    f.write('  "%s",\n' % name)
  f.write("};\n")
  f.write("static void *targets[%d];\n" % len(funcs))
  f.write("void mana_fwd_%s_on_upper(void) __attribute__((weak));\n" % prefix)
  f.write('__attribute__((visibility("hidden")))\n')
  f.write('FwdLib %s = { "%s", names, targets, %d, mana_fwd_%s_on_upper, 0 };\n\n'
          % (desc, soname, len(funcs), prefix))
  for name in data:
    f.write("char %s[64];\n" % name)
# The shim's symbols get the real library's (default) versions, so that
# programs linked with versioned symbols find them.
with open(os.path.join(out_dir, prefix + ".map"), "w") as f:
  if versions:
    for node, names in versions.items():
      f.write("%s {\n  global:\n" % node)
      for name in sorted(set(names)):
        f.write("    %s;\n" % name)
      f.write("};\n")
  else:
    f.write("{ global: *; };\n")
print("%s: %d functions, %d data symbols, %d excluded"
      % (prefix, len(funcs), len(data), len(excluded)))
