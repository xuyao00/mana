/*
 * The runtime of MANA's forwarding shims (libmana_fwd.so, in the lower half).
 *
 * The CUDA checkpoint API supports one CUDA driver per process, and that
 * driver must be the upper half's: MANA replaces the lower half at restart.
 * So the lower half's MPI (UCX, MPICH's yaksa, Cray's GTL, libfabric) is
 * given shims of libcuda.so.1, libcudart.so.<N> and libnvidia-ml.so.1, whose
 * every function forwards to the same function of the upper half's library.
 * The MPI then works on the application's device memory, in the
 * application's CUDA contexts, as a CUDA-aware MPI does natively.  See
 * README.md.
 *
 * A forwarded call runs upper-half code, so it must run with the upper
 * half's FS register (TLS).  Each shim function is a trampoline (generated by
 * gen-forward-shim.py; see fwd-tramp.inc): it calls mana_fwd_enter(), which
 * finds the calling thread and its upper-half FS, switches FS and jumps to
 * the upper half's function; that function returns into the trampoline,
 * which switches FS back.
 *
 * While in the lower half, all upper-half threads use the lower half's main
 * TLS, so the per-thread state here is in a table, not in TLS.  MANA
 * registers each upper-half thread with its stack range (register_thread()),
 * and a forwarded call finds its thread by its stack pointer, without a
 * system call.  A thread that the lower half created itself (e.g. UCX's
 * progress thread) is found by its tid; it has no upper half, and its
 * forwarded calls fail with "no device".
 */

#define _GNU_SOURCE
#include <asm/prctl.h>
#include <fcntl.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/syscall.h>
#include <unistd.h>

#include "fwd-runtime.h"

#define MAX_THREADS 256
#define MAX_DEPTH 16          // forwarded calls in progress per thread
#define MAX_DYN_SLOTS 4096    // see fwd-dyn.S

#define TID_FREE 0
#define TID_DELETED (-1)

typedef struct {
  volatile int tid;           // or TID_FREE, TID_DELETED
  unsigned long uhfs;         // 0: no upper half (a lower-half thread)
  unsigned long stack_lo, stack_hi;   // its stack, if known
  int depth;
  FwdRecord recs[MAX_DEPTH];
} FwdThread;

// An open-addressing hash table by tid.  Lookups take no lock; changes take
// threads_lock.
static FwdThread threads[MAX_THREADS];
// The threads with a known stack.  Entries are only added (under
// threads_lock), each FwdThread once; a forgotten thread's range is empty.
static FwdThread *by_stack[MAX_THREADS];
static int n_by_stack;
static int threads_lock;

FwdCtl mana_fwd_ctl;
int mana_fwd_fsgsbase = 0;    // read by the trampolines

static void
lock_threads(void)
{
  while (__atomic_test_and_set(&threads_lock, __ATOMIC_ACQUIRE)) {
    __builtin_ia32_pause();
  }
}

static void
unlock_threads(void)
{
  __atomic_clear(&threads_lock, __ATOMIC_RELEASE);
}

static long
raw_syscall2(long nr, long a, long b)
{
  long ret;
  asm volatile("syscall" : "=a"(ret) : "0"(nr), "D"(a), "S"(b)
               : "rcx", "r11", "memory");
  return ret;
}

static int
fwd_gettid(void)
{
  long ret;
  asm volatile("syscall" : "=a"(ret) : "0"(SYS_gettid)
               : "rcx", "r11", "memory");
  return (int)ret;
}

static unsigned long
fwd_getfs(void)
{
  unsigned long fs;
  if (mana_fwd_fsgsbase) {
    asm volatile("rdfsbase %0" : "=r"(fs));
  } else {
    raw_syscall2(SYS_arch_prctl, ARCH_GET_FS, (long)&fs);
  }
  return fs;
}

static void
fwd_setfs(unsigned long fs)
{
  if (mana_fwd_fsgsbase) {
    asm volatile("wrfsbase %0" : : "r"(fs) : "memory");
  } else {
    raw_syscall2(SYS_arch_prctl, ARCH_SET_FS, (long)fs);
  }
}

// MANA_FWD_VERBOSE: log what the shims do.
int
mana_fwd_verbose(void)
{
  static int verbose = -1;
  if (verbose < 0) {
    const char *v = getenv("MANA_FWD_VERBOSE");
    verbose = v != NULL && v[0] != '\0' && v[0] != '0';
  }
  return verbose;
}

static void
fwd_log(const char *fmt, const char *a, const char *b)
{
  if (mana_fwd_verbose()) {
    char buf[512];
    int n = snprintf(buf, sizeof buf, "[mana-fwd %d] ", fwd_gettid());
    n += snprintf(buf + n, sizeof buf - n, fmt, a, b);
    if (n > (int)sizeof buf - 1) {
      n = sizeof buf - 1;
    }
    if (write(2, buf, n) < 0) {
      return;
    }
  }
}

static FwdThread *
find_thread(int tid)
{
  unsigned h = (unsigned)tid % MAX_THREADS;
  for (int i = 0; i < MAX_THREADS; i++) {
    FwdThread *t = &threads[(h + i) % MAX_THREADS];
    if (t->tid == tid) {
      return t;
    }
    if (t->tid == TID_FREE) {
      return NULL;
    }
  }
  return NULL;
}

// The entry of 'tid', added if needed.  With threads_lock.
static FwdThread *
add_thread(int tid)
{
  FwdThread *t = find_thread(tid);
  if (t != NULL) {
    return t;
  }
  unsigned h = (unsigned)tid % MAX_THREADS;
  for (int i = 0; i < MAX_THREADS; i++) {
    t = &threads[(h + i) % MAX_THREADS];
    if (t->tid == TID_FREE || t->tid == TID_DELETED) {
      t->uhfs = 0;
      t->stack_lo = t->stack_hi = 0;
      t->depth = 0;
      __atomic_store_n(&t->tid, tid, __ATOMIC_RELEASE);
      return t;
    }
  }
  return NULL;
}

static void
fwd_register_thread(int tid, unsigned long uhfs, unsigned long lo,
                    unsigned long hi)
{
  lock_threads();
  FwdThread *t = add_thread(tid);
  if (t == NULL) {
    unlock_threads();
    return;
  }
  t->uhfs = uhfs;
  if (lo < hi) {
    // A dead thread's stack may be reused by this one.
    for (int i = 0; i < n_by_stack; i++) {
      FwdThread *o = by_stack[i];
      if (o != t && o->stack_lo < hi && lo < o->stack_hi) {
        o->stack_lo = o->stack_hi = 0;
      }
    }
    t->stack_lo = lo;
    t->stack_hi = hi;
    int listed = 0;
    for (int i = 0; i < n_by_stack; i++) {
      listed = listed || by_stack[i] == t;
    }
    if (!listed && n_by_stack < MAX_THREADS) {
      by_stack[n_by_stack] = t;
      __atomic_store_n(&n_by_stack, n_by_stack + 1, __ATOMIC_RELEASE);
    }
  }
  unlock_threads();
}

static void
fwd_forget_thread(int tid)
{
  lock_threads();
  FwdThread *t = find_thread(tid);
  if (t != NULL) {
    t->stack_lo = t->stack_hi = 0;
    t->uhfs = 0;
    __atomic_store_n(&t->tid, TID_DELETED, __ATOMIC_RELEASE);
  }
  unlock_threads();
}

// The fast trampolines (fwd-tramp.inc) use these offsets.
_Static_assert(offsetof(FwdThread, uhfs) == 8, "FwdThread.uhfs");
_Static_assert(offsetof(FwdThread, depth) == 32, "FwdThread.depth");

// No vector registers: mana_fwd_fast_enter() uses it, and must keep the
// caller's arguments in the vector registers.
__attribute__((target("general-regs-only"))) static inline FwdThread *
thread_by_stack(unsigned long sp)
{
  int n = __atomic_load_n(&n_by_stack, __ATOMIC_ACQUIRE);
  for (int i = 0; i < n; i++) {
    FwdThread *t = by_stack[i];
    if (sp >= t->stack_lo && sp < t->stack_hi) {
      return t;
    }
  }
  return NULL;
}

// The calling thread, whose stack holds 'sp'.  A thread that MANA did not
// register (a lower-half thread) gets an entry without an upper half if
// 'create'.
static FwdThread *
current_thread(unsigned long sp, int create)
{
  FwdThread *t = thread_by_stack(sp);
  if (t != NULL) {
    return t;
  }
  int tid = fwd_gettid();
  t = find_thread(tid);
  if (t == NULL && create) {
    lock_threads();
    t = add_thread(tid);
    unlock_threads();
  }
  return t;
}

// The result of a call that cannot be forwarded: CUresult and cudaError_t
// both say "no device" with 100.
static long
fwd_unavailable(void)
{
  return 100;
}

static void *
resolve(FwdLib *lib, int idx, unsigned long uhfs, unsigned long lhfs)
{
  void *target = lib->targets[idx];
  if (target != NULL) {
    return target;
  }
  if (mana_fwd_ctl.uh_dlsym == NULL || uhfs == 0) {
    return NULL;
  }
  if (!lib->upper_seen) {
    lib->upper_seen = 1;
    if (lib->on_upper != NULL) {
      lib->on_upper();
    }
  }
  fwd_setfs(uhfs);
  target = mana_fwd_ctl.uh_dlsym(lib->soname, lib->names[idx]);
  fwd_setfs(lhfs);
  if (target == NULL) {
    fwd_log("cannot resolve %s in the upper half's %s\n",
            lib->names[idx], lib->soname);
  } else {
    fwd_log("forwarding %s (%s)\n", lib->names[idx], lib->soname);
  }
  lib->targets[idx] = target;
  return target;
}

// Forwarded calls, for MANA_FWD_VERBOSE (not exact: not atomic).
static unsigned long n_calls;

// MANA_FWD_PROFILE=1: calls and TSC cycles in each forwarded function (not
// exact either), printed at exit, most called first.
#define MAX_PROF_LIBS 8
typedef struct {
  int calls;                  // first: FwdRecord.prof points here
  unsigned long cycles;
} FwdProf;
// -1: MANA_FWD_PROFILE not looked up yet.
int mana_fwd_profiling = -1;
static FwdLib *prof_libs[MAX_PROF_LIBS];
static FwdProf *prof_tabs[MAX_PROF_LIBS];
static FwdProf *prof_entry(FwdLib *lib, int idx);

// The hand-written wrappers' upper-half calls (FWD_CALL_UPPER), by the name
// of the wrapper: one more "library".
#define MAX_PROF_SPECIAL 64
static const char *special_names[MAX_PROF_SPECIAL];
static FwdLib special_lib = { "(hand-written)", special_names, NULL,
                              MAX_PROF_SPECIAL, NULL, 0 };

void
mana_fwd_prof_special(const char *func, unsigned long t0)
{
  int i;
  for (i = 0; i < MAX_PROF_SPECIAL && special_names[i] != NULL &&
              special_names[i] != func; i++) {
  }
  if (i == MAX_PROF_SPECIAL) {
    return;
  }
  special_names[i] = func;
  FwdProf *p = prof_entry(&special_lib, i);
  if (p != NULL) {
    p->calls++;
    p->cycles += __builtin_ia32_rdtsc() - t0;
  }
}

static FwdProf *
prof_entry(FwdLib *lib, int idx)
{
  for (int i = 0; i < MAX_PROF_LIBS; i++) {
    if (prof_libs[i] == lib) {
      return &prof_tabs[i][idx];
    }
    if (prof_libs[i] == NULL) {
      prof_tabs[i] = calloc(lib->n, sizeof(FwdProf));
      if (prof_tabs[i] == NULL) {
        return NULL;
      }
      prof_libs[i] = lib;
      return &prof_tabs[i][idx];
    }
  }
  return NULL;
}

static void
prof_report(void)
{
  char buf[256];
  for (;;) {
    FwdProf *best = NULL;
    const char *name = NULL;
    for (int i = 0; i < MAX_PROF_LIBS && prof_libs[i] != NULL; i++) {
      for (int j = 0; j < prof_libs[i]->n; j++) {
        FwdProf *p = &prof_tabs[i][j];
        if (prof_libs[i]->names[j] == NULL) {
          continue;
        }
        if (p->calls > 0 && (best == NULL || p->calls > best->calls)) {
          best = p;
          name = prof_libs[i]->names[j];
        }
      }
    }
    if (best == NULL) {
      return;
    }
    int n = snprintf(buf, sizeof buf, "[mana-fwd %d] profile %10d calls "
                     "%14lu cycles %s\n", fwd_gettid(), best->calls,
                     best->cycles, name);
    if (write(2, buf, n) < 0) {
      return;
    }
    best->calls = 0;
  }
}

__attribute__((destructor)) static void
fwd_report(void)
{
  if (mana_fwd_verbose()) {
    char buf[128];
    int n = snprintf(buf, sizeof buf, "[mana-fwd %d] %lu forwarded calls\n",
                     fwd_gettid(), n_calls);
    if (write(2, buf, n) < 0) {
      return;
    }
  }
  if (mana_fwd_profiling > 0) {
    prof_report();
  }
}

// Called by the trampolines (lower half, lower-half FS) for slot 'idx' of
// 'lib'; 'retslot' holds the caller's return address.
FwdRecord *
mana_fwd_enter(FwdLib *lib, long idx, void **retslot)
{
  n_calls++;
  FwdThread *t = current_thread((unsigned long)retslot, 1);
  unsigned long lhfs = fwd_getfs();
  if (t == NULL || t->depth >= MAX_DEPTH) {
    fprintf(stderr, "[mana-fwd %d] FATAL: thread table full or calls nested "
            "too deep (%s)\n", fwd_gettid(), lib->names[idx]);
    abort();
  }
  FwdRecord *r = &t->recs[t->depth++];
  r->ret = *retslot;
  r->lhfs = lhfs;
  r->prof = NULL;
  if (mana_fwd_profiling != 0) {
    if (mana_fwd_profiling < 0) {
      const char *v = getenv("MANA_FWD_PROFILE");
      mana_fwd_profiling = v != NULL && v[0] != '\0' && v[0] != '0';
    }
    if (mana_fwd_profiling > 0) {
      r->prof = &prof_entry(lib, (int)idx)->calls;
      r->t0 = __builtin_ia32_rdtsc();
    }
  }
  void *target = resolve(lib, (int)idx, t->uhfs, lhfs);
  if (target == NULL || t->uhfs == 0) {
    if (t->uhfs == 0) {
      fwd_log("%s called on a thread without an upper half (%s)\n",
              lib->names[idx], lib->soname);
    }
    r->target = (void *)fwd_unavailable;
    r->uhfs = lhfs;           // no FS switch
  } else {
    r->target = target;
    r->uhfs = t->uhfs;
  }
  return r;
}

// Called by the fast trampolines (FWD_FAST_SLOT, lower-half FS) for slot
// 'idx' of 'lib'.  The fast path is taken only in the common case: the target
// is resolved, the thread is known by its stack and has an upper half, and
// wrfsbase works.  Then this counts the call in the thread's depth (the
// trampoline counts it out), and returns the target and the thread;
// otherwise it returns no target, and the trampoline takes the general path.
// It must not touch the vector registers, which may hold arguments.
typedef struct {
  void *target;
  FwdThread *thread;
} FwdFast;

__attribute__((target("general-regs-only"))) FwdFast
mana_fwd_fast_enter(FwdLib *lib, long idx, void **retslot)
{
  FwdFast f = { NULL, NULL };
  // mana_fwd_profiling < 0: not looked up yet; the general path does that.
  if (!mana_fwd_fsgsbase || mana_fwd_profiling != 0) {
    return f;
  }
  void *target = lib->targets[idx];
  FwdThread *t = thread_by_stack((unsigned long)retslot);
  if (target == NULL || t == NULL || t->uhfs == 0 || t->depth >= MAX_DEPTH) {
    return f;
  }
  t->depth++;
  n_calls++;
  f.target = target;
  f.thread = t;
  return f;
}

// Called by the trampolines when the forwarded call returned.
void
mana_fwd_exit(FwdRecord *r)
{
  FwdThread *t = &threads[((char *)r - (char *)threads) / sizeof(FwdThread)];
  if (r->prof != NULL) {
    FwdProf *p = (FwdProf *)r->prof;
    p->calls++;
    p->cycles += __builtin_ia32_rdtsc() - r->t0;
  }
  if (t->depth > 0 && &t->recs[t->depth - 1] == r) {
    t->depth--;
  }
}

// This thread's upper-half FS, or 0 if it has no upper half.
unsigned long
mana_fwd_uhfs(void)
{
  int here;
  FwdThread *t = current_thread((unsigned long)&here, 0);
  return t != NULL ? t->uhfs : 0;
}

void
mana_fwd_switch(unsigned long fs)
{
  fwd_setfs(fs);
}

unsigned long
mana_fwd_current_fs(void)
{
  return fwd_getfs();
}

// Upper-half function pointers that the lower half gets (cuGetProcAddress,
// cudaGetDriverEntryPoint, private tables) must be called through a
// trampoline, too: the slots of the 'dynamic' library, defined in fwd-dyn.S.
static const char *dyn_names[MAX_DYN_SLOTS];
static void *dyn_targets[MAX_DYN_SLOTS];
__attribute__((visibility("hidden")))
FwdLib mana_fwd_dyn_lib = { "(dynamic)", dyn_names, dyn_targets,
                            MAX_DYN_SLOTS, NULL, 0 };
extern char mana_fwd_dyn_tramp[];   // MAX_DYN_SLOTS entries, 16 bytes each
static int n_dyn = 0;
static int dyn_lock;

// The trampoline of upper-half function 'upper_fn'.
void *
mana_fwd_wrap_ptr(void *upper_fn, const char *name)
{
  if (upper_fn == NULL) {
    return NULL;
  }
  while (__atomic_test_and_set(&dyn_lock, __ATOMIC_ACQUIRE)) {
    __builtin_ia32_pause();
  }
  int i;
  for (i = 0; i < n_dyn && dyn_targets[i] != upper_fn; i++) {
  }
  if (i == n_dyn) {
    if (n_dyn == MAX_DYN_SLOTS) {
      fprintf(stderr, "[mana-fwd] FATAL: out of dynamic trampolines\n");
      abort();
    }
    dyn_names[i] = strdup(name != NULL ? name : "(pointer)");
    dyn_targets[i] = upper_fn;
    __atomic_store_n(&n_dyn, n_dyn + 1, __ATOMIC_RELEASE);
  }
  __atomic_clear(&dyn_lock, __ATOMIC_RELEASE);
  return mana_fwd_dyn_tramp + 16 * i;
}

// The lower half's host-memory registrations, which the libcuda and the
// libcudart shim record.
#define MAX_HOST_REGS 4096
static HostReg host_regs[MAX_HOST_REGS];
static int n_host_regs;
static int host_regs_lock;

void
mana_fwd_note_host_register(void *ptr, size_t size, unsigned flags, void *ctx)
{
  while (__atomic_test_and_set(&host_regs_lock, __ATOMIC_ACQUIRE)) {
    __builtin_ia32_pause();
  }
  int i;
  for (i = 0; i < n_host_regs && host_regs[i].on; i++) {
  }
  if (i < MAX_HOST_REGS) {
    host_regs[i] = (HostReg){ ptr, size, flags, ctx, 1 };
    if (i == n_host_regs) {
      n_host_regs++;
    }
  } else {
    fprintf(stderr, "[mana-fwd] too many host registrations: %p stays "
            "registered at a checkpoint\n", ptr);
  }
  __atomic_clear(&host_regs_lock, __ATOMIC_RELEASE);
}

void
mana_fwd_note_host_unregister(void *ptr)
{
  while (__atomic_test_and_set(&host_regs_lock, __ATOMIC_ACQUIRE)) {
    __builtin_ia32_pause();
  }
  for (int i = 0; i < n_host_regs; i++) {
    if (host_regs[i].on && host_regs[i].ptr == ptr) {
      host_regs[i].on = 0;
      break;
    }
  }
  __atomic_clear(&host_regs_lock, __ATOMIC_RELEASE);
}

// For the checkpoint hooks, which run while no other thread is in the
// lower half.
HostReg *
mana_fwd_host_regs(int *n)
{
  *n = n_host_regs;
  return host_regs;
}

