/*
 * Private function tables (cuGetExportTable, nvmlInternalGetExportTable).
 * Their layout is not documented, but every table seen so far starts with
 * its size in bytes, followed by pointers.  The copy that the lower half
 * gets has a trampoline for each entry that points into the code of the
 * library that contains 'lib_fn' (an upper-half function).
 */
typedef struct { unsigned long lo, hi; } Range;

// The executable mappings of the file that contains address 'a'.
static int
code_ranges(unsigned long a, Range *ranges, int max)
{
  int n = 0;
  int fd = open("/proc/self/maps", O_RDONLY);
  if (fd < 0) {
    return 0;
  }
  char buf[1 << 16], line[1024], path[512] = "";
  for (int pass = 0; pass < 2; pass++) {    // 0: find the file; 1: its code
    lseek(fd, 0, SEEK_SET);
    ssize_t nr, len = 0;
    while ((nr = read(fd, buf, sizeof buf)) > 0) {
      for (ssize_t i = 0; i < nr; i++) {
        if (buf[i] != '\n') {
          if (len < (ssize_t)sizeof line - 1) {
            line[len++] = buf[i];
          }
          continue;
        }
        line[len] = '\0';
        len = 0;
        unsigned long lo, hi;
        char perms[8], p[512] = "";
        if (sscanf(line, "%lx-%lx %7s %*s %*s %*s %511s",
                   &lo, &hi, perms, p) < 3) {
          continue;
        }
        if (pass == 0 && a >= lo && a < hi) {
          strcpy(path, p);
        } else if (pass == 1 && perms[2] == 'x' && path[0] != '\0' &&
                   strcmp(p, path) == 0 && n < max) {
          ranges[n].lo = lo;
          ranges[n].hi = hi;
          n++;
        }
      }
    }
  }
  close(fd);
  return n;
}

typedef struct { const void *real; void *copy; } Table;
static Table tables[128];
static int n_tables;
static int tables_lock;

static const void *wrap_table(const void *table, void *lib_fn,
                              const void *uuid);

const void *
mana_fwd_wrap_table(const void *table, void *lib_fn, const void *uuid)
{
  while (__atomic_test_and_set(&tables_lock, __ATOMIC_ACQUIRE)) {
    __builtin_ia32_pause();
  }
  const void *copy = wrap_table(table, lib_fn, uuid);
  __atomic_clear(&tables_lock, __ATOMIC_RELEASE);
  return copy;
}

static const void *
wrap_table(const void *table, void *lib_fn, const void *uuid)
{
  for (int i = 0; i < n_tables; i++) {
    if (tables[i].real == table) {
      return tables[i].copy;
    }
  }
  unsigned long size = *(const unsigned long *)table;
  if (size < 8 || size > 65536 || size % 8 != 0 || n_tables == 128) {
    fprintf(stderr, "[mana-fwd] export table with first word %lu: "
            "not wrapped\n", size);
    return table;
  }
  Range code[16];
  int n_code = code_ranges((unsigned long)lib_fn, code, 16);
  unsigned long *copy = (unsigned long *)malloc(size);
  memcpy(copy, table, size);
  int wrapped = 0;
  for (unsigned long i = 1; i < size / 8; i++) {
    for (int j = 0; j < n_code; j++) {
      if (copy[i] >= code[j].lo && copy[i] < code[j].hi) {
        copy[i] = (unsigned long)mana_fwd_wrap_ptr((void *)copy[i],
                                                   "(export table)");
        wrapped++;
        break;
      }
    }
  }
  if (mana_fwd_verbose()) {
    const unsigned char *u = (const unsigned char *)uuid;
    fprintf(stderr, "[mana-fwd] export table %02x%02x%02x%02x...: %lu bytes, "
            "%d of %lu entries wrapped\n", u[0], u[1], u[2], u[3], size,
            wrapped, size / 8 - 1);
  }
  tables[n_tables].real = table;
  tables[n_tables].copy = copy;
  n_tables++;
  return copy;
}
