#!/usr/bin/env python3
"""Generate a stub libcuda.so.1 for MANA's lower half.

The lower half's MPI (and libraries it links, e.g. hwloc in hydra) may link or
dlopen libcuda.  The CUDA checkpoint API handles only one CUDA driver instance
per process, and it must be the upper half's.  So the lower half gets this
stub: every entry point exists (same symbols as the real driver) and reports
CUDA_ERROR_NO_DEVICE; cuGetProcAddress hands out such entry points, so
cudart reports "no CUDA-capable device" and MPI initializes without GPUs.

  gen-stub.py [/path/to/real/libcuda.so.1] > stub.c
  gcc -shared -fPIC -fno-builtin -o libcuda.so.1 stub.c -Wl,-soname,libcuda.so.1

Run the lower half with this directory first in LD_LIBRARY_PATH and
MANA_LH_ONLY_LIBRARY_PATH=<this directory> (the lower half removes it from
LD_LIBRARY_PATH before it loads the upper half).
"""
import subprocess
import sys

real = sys.argv[1] if len(sys.argv) > 1 else "/usr/lib/x86_64-linux-gnu/libcuda.so.1"
nm = subprocess.run(["nm", "-D", "--defined-only", real],
                    stdout=subprocess.PIPE, universal_newlines=True,
                    check=True).stdout

special = {
  "cuDriverGetVersion":
    "int cuDriverGetVersion(int *v) { if (v) *v = 13020; return 0; }",
  "cuGetErrorString":
    'int cuGetErrorString(int e, const char **s) '
    '{ if (s) *s = "no CUDA device (MANA lower-half stub)"; return 0; }',
  "cuGetErrorName":
    'int cuGetErrorName(int e, const char **s) '
    '{ if (s) *s = "CUDA_ERROR_NO_DEVICE"; return 0; }',
  "cuDeviceGetCount":
    "int cuDeviceGetCount(int *n) { if (n) *n = 0; return 100; }",
  "cuGetProcAddress": None,      # defined below
  "cuGetProcAddress_v2": None,
}

print("""// Generated by gen-stub.py: stub libcuda.so.1 for MANA's lower half.
// Every entry point fails with CUDA_ERROR_NO_DEVICE (100).
#include <string.h>
static int stub_nodev(void) { return 100; }
int cuDriverGetVersion(int *v);
int cuGetErrorString(int e, const char **s);
int cuGetErrorName(int e, const char **s);
int cuDeviceGetCount(int *n);
int cuGetProcAddress_v2(const char *sym, void **pfn, int ver,
                        unsigned long long flags, int *status);
static void *lookup(const char *sym) {
  if (!strcmp(sym, "cuDriverGetVersion")) return (void*)cuDriverGetVersion;
  if (!strcmp(sym, "cuGetErrorString")) return (void*)cuGetErrorString;
  if (!strcmp(sym, "cuGetErrorName")) return (void*)cuGetErrorName;
  if (!strcmp(sym, "cuDeviceGetCount")) return (void*)cuDeviceGetCount;
  if (!strcmp(sym, "cuGetProcAddress")) return (void*)cuGetProcAddress_v2;
  return (void*)stub_nodev;
}
int cuGetProcAddress_v2(const char *sym, void **pfn, int ver,
                        unsigned long long flags, int *status) {
  if (pfn) *pfn = lookup(sym);
  if (status) *status = 0;
  return 0;
}
int cuGetProcAddress(const char *sym, void **pfn, int ver,
                     unsigned long long flags) {
  if (pfn) *pfn = lookup(sym);
  return 0;
}""")
seen = set()
for line in nm.splitlines():
  parts = line.split()
  if len(parts) != 3:
    continue
  kind, name = parts[1], parts[2].split("@")[0]
  if name in seen:
    continue
  seen.add(name)
  if kind == "T":
    if name in special:
      if special[name]:
        print(special[name])
    else:
      print("int %s(void) { return 100; }" % name)
  elif kind in "BD":
    print("char %s[64];" % name)
